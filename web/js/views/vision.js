import { banner, errorBox, meter, pageHead } from '../ui.js';
import { clear, el, fmtPct, toast } from '../util.js';

const CLASSES = ['electronics', 'fashion', 'grocery', 'home', 'beauty', 'sports'];

export async function render(root, { api, mode }) {
  root.appendChild(pageHead('Image classifier', 'A small CNN/MLP that assigns a product category to a tile image. Trained on synthetic icons, so it shows the pipeline, not real-photo performance.'));
  const demo = mode === 'demo';
  if (demo) root.appendChild(banner('Static demo: click a sample tile to see its pre-computed prediction. Uploads need the live backend.', 'info', 'Static demo.'));
  const out = el('div', { class: 'card' }, el('p', { class: 'sub' }, 'Pick a sample tile or upload a PNG/JPEG (max 200 KB).'));
  let selected = null;

  function show(res, src) {
    clear(out);
    out.append(el('div', { class: 'row' }, el('img', { class: 'preview', src, alt: 'Image being classified' }),
      el('div', { class: 'stack', style: { flex: '1', minWidth: '220px' } }, el('h3', {}, 'Top predictions'),
        res.predictions.map((p, i) => el('div', { class: 'prob' }, el('span', {}, p.category), meter(p.probability, i === 0 ? '' : 'warn'), el('b', {}, fmtPct(p.probability * 100, 1))))),
      ), el('p', { class: 'sub' }, `Backend: ${res.backend}. Probabilities are model confidence on synthetic icons, not calibrated for real photos.`));
  }
  async function classifySample(name, btn) {
    selected && selected.setAttribute('aria-pressed', 'false');
    btn.setAttribute('aria-pressed', 'true'); selected = btn;
    const src = `samples/${name}.png`;
    try {
      const blob = demo ? null : await (await fetch(src)).blob();
      show(await api.classify(blob, name), src);
    } catch (e) { clear(out); out.appendChild(errorBox(e)); }
  }
  const gallery = el('div', { class: 'tiles-gallery' });
  CLASSES.forEach((c) => [1, 2].forEach((k) => {
    const name = `${c}_${k}`;
    const b = el('button', { class: 'sample', type: 'button', 'aria-pressed': 'false', 'aria-label': `Sample tile ${name.replace('_', ' ')}` }, el('img', { src: `samples/${name}.png`, alt: '' }));
    b.addEventListener('click', () => classifySample(name, b));
    gallery.appendChild(b);
  }));

  const file = el('input', { type: 'file', accept: 'image/png,image/jpeg', 'aria-label': 'Upload an image', disabled: demo });
  file.addEventListener('change', async () => {
    const f = file.files[0];
    if (!f) return;
    if (f.size > 200_000) { toast('Image is larger than 200 KB', 'error'); return; }
    const url = URL.createObjectURL(f);
    try { show(await api.classify(f, f.name), url); } catch (e) { clear(out); out.appendChild(errorBox(e)); }
  });

  root.append(el('div', { class: 'grid cols-2' },
    el('section', { class: 'card' }, el('h3', {}, 'Sample tiles'), el('p', { class: 'sub' }, 'Two per class, generated by the project (original icons, no real products).'), gallery,
      el('div', { class: 'drop', style: { marginTop: '14px' } }, el('p', {}, demo ? 'Uploads are disabled in the static demo.' : 'Upload your own tile'), file)),
    out));
  try {
    const s = await api.summary();
    root.appendChild(el('p', { class: 'sub', style: { marginTop: '14px' } }, `Held-out accuracy on synthetic tiles: ${fmtPct(s.vision.accuracy * 100)} (${s.vision.backend}). Classes: ${s.vision.classes.join(', ')}.`));
  } catch { /* summary is optional here */ }
}
